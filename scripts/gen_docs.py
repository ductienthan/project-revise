"""Generate the reference docs from the code, so they cannot drift from it.

    uv run python scripts/gen_docs.py           # write docs/cli.md, configuration.md, api.md, data-model.md
    uv run python scripts/gen_docs.py --check   # exit 1 if any of them is out of date
"""

import argparse
import sys
from pathlib import Path

import click

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from preflight.cli.main import cli
from preflight.cli.project import project
from preflight.config import Settings
from preflight.db.base import Base, UTCDateTime
from preflight.server.main import create_app

GENERATED = "<!-- Generated by scripts/gen_docs.py. Do not edit by hand. -->"

CLI_ENV = [
    ("PREFLIGHT_API_URL", "http://localhost:8000", "Address of the Preflight server the CLI talks to."),
    ("PREFLIGHT_CONFIG_DIR", "~/.config/preflight", "Where the CLI keeps its offline queue, and its token file when the keyring is off."),
    ("PREFLIGHT_NO_KEYRING", "unset", "Set to `1` to store tokens in a file readable only by you instead of the OS keyring."),
]
TOOL_ENV = [
    ("PREFLIGHT_ADMIN_PASSWORD", "unset", "Password for `preflight-server create-user`, instead of the prompt."),
    ("PREFLIGHT_TEST_DATABASE_URL", "sqlite://", "Database for `pytest`. The tests drop and recreate every table."),
    ("PREFLIGHT_E2E_DATABASE_URL", "a temporary SQLite file", "Database for `scripts/e2e.py`."),
    ("PREFLIGHT_UPDATE_GOLDEN", "unset", "Set to `1` to rewrite `tests/golden/review_payload.txt`."),
    ("PREFLIGHT_TEST_OLLAMA", "unset", "Set to `1` to run the test that calls a real local Ollama."),
]


def _help(command: click.Command, path: str) -> str:
    with click.Context(command, info_name=path, terminal_width=100, max_content_width=100) as ctx:
        return command.get_help(ctx)


def cli_doc() -> str:
    lines = ["# CLI reference", "", GENERATED, "",
             "The command is `preflight`. Project work follows `preflight <project> <action>`. Every other command is a word",
             "that cannot be used as a project name. See [configuration](configuration.md) for the environment variables the",
             "CLI reads.", "", "## Commands", ""]
    for name, command in sorted(cli.commands.items()):
        if name == "project":
            continue
        lines += [f"### preflight {name}", "", "```text", _help(command, f"preflight {name}"), "```", ""]
        if isinstance(command, click.Group):
            for sub_name, sub in sorted(command.commands.items()):
                lines += [f"#### preflight {name} {sub_name}", "", "```text", _help(sub, f"preflight {name} {sub_name}"), "```", ""]
    lines += ["## Project actions", "", "Run these as `preflight <project> <action>`.", ""]
    for name, command in sorted(project.commands.items()):
        lines += [f"### preflight &lt;project&gt; {name}", "", "```text", _help(command, f"preflight <project> {name}"), "```", ""]
    return "\n".join(lines).rstrip() + "\n"


def _default(value) -> str:
    if value is None:
        return "unset"
    return f"`{value}`"


def configuration_doc() -> str:
    lines = ["# Configuration", "", GENERATED, "",
             "## Server", "",
             "The server reads these from the environment or from a `.env` file in its working directory.", "",
             "| Variable | Default | Meaning |", "|---|---|---|"]
    for name, field in Settings.model_fields.items():
        lines.append(f"| `PREFLIGHT_{name.upper()}` | {_default(field.default)} | {field.description} |")
    lines += ["", "## CLI", "", "| Variable | Default | Meaning |", "|---|---|---|"]
    lines += [f"| `{n}` | {d} | {m} |" for n, d, m in CLI_ENV]
    lines += ["", "## Tools and tests", "", "| Variable | Default | Meaning |", "|---|---|---|"]
    lines += [f"| `{n}` | {d} | {m} |" for n, d, m in TOOL_ENV]
    return "\n".join(lines) + "\n"


def api_doc() -> str:
    schema = create_app(Settings(database_url="sqlite://", _env_file=None)).openapi()
    lines = ["# API reference", "", GENERATED, "",
             "Every endpoint is under `/api/v1` and needs a dashboard session cookie (with an `X-CSRF-Token` header on writes)",
             "or a CLI bearer token. The login, device-code, token, and refresh endpoints are the exceptions. A running server",
             "does not publish interactive docs.", "",
             "| Area | Method | Path | Handler |", "|---|---|---|---|"]
    rows = []
    for path, operations in schema["paths"].items():
        for method, op in operations.items():
            rows.append((op.get("tags", ["other"])[0], path.removeprefix("/api/v1"), method.upper(), op.get("summary", "")))
    lines += [f"| {tag} | `{method}` | `{path}` | {summary} |" for tag, path, method, summary in sorted(rows)]
    return "\n".join(lines) + "\n"


def data_model_doc() -> str:
    lines = ["# Data model", "", GENERATED, "",
             "Every table except `users` has a UUID `id`, a `user_id`, and a `created_at` stamped from the server clock.",
             "Migrations live in `src/preflight/db/migrations/versions/`.", ""]
    for table in sorted(Base.metadata.tables.values(), key=lambda t: t.name):
        lines += [f"## {table.name}", "", "| Column | Type | Null | References |", "|---|---|---|---|"]
        for column in table.columns:
            refs = ", ".join(f"`{fk.target_fullname}`" for fk in column.foreign_keys)
            kind = "UTC datetime" if isinstance(column.type, UTCDateTime) else column.type.__class__.__name__
            lines.append(f"| `{column.name}` | {kind} | {'yes' if column.nullable else 'no'} | {refs} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


DOCS = {"cli.md": cli_doc, "configuration.md": configuration_doc, "api.md": api_doc, "data-model.md": data_model_doc}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, render in DOCS.items():
        path = ROOT / "docs" / name
        text = render()
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
            print(f"Wrote docs/{name}")
    if stale:
        print(f"Out of date: {', '.join(stale)}. Run `uv run python scripts/gen_docs.py`.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
